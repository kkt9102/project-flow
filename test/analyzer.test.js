'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { analyze, inside, secret } = require('../src/analyzer');
test('imports, re-exports, require, dynamic imports, aliases and assets', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'project-flow-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  await fs.mkdir(path.join(root, 'src'));
  await fs.mkdir(path.join(root, 'node_modules'));
  await fs.mkdir(path.join(root, 'node_modules', 'react'));
  await fs.writeFile(path.join(root, 'tsconfig.json'), JSON.stringify({ compilerOptions: { baseUrl: '.', paths: { '@/*': ['src/*'] } } }));
  await fs.writeFile(path.join(root, 'entry.ts'), "import { x } from '@/src'; export * from './other'; const a = require('./dynamic'); import('./lazy'); import './style.css'; import React from 'react'; // import './fake'\n");
  for (const name of ['other.ts', 'dynamic.ts', 'lazy.ts', 'fake.ts', 'style.css']) await fs.writeFile(path.join(root, name), '');
  await fs.writeFile(path.join(root, 'src', 'src.ts'), 'export const x = 1;');
  await fs.writeFile(path.join(root, 'node_modules', 'react', 'index.d.ts'), 'export default function React(): void;');
  await fs.writeFile(path.join(root, '.env.local'), '');
  await fs.symlink(os.tmpdir(), path.join(root, 'outside'));
  const graph = await analyze(root, root, false);
  const targetNames = graph.edges.filter(e => e.source.endsWith('entry.ts')).map(e => path.basename(e.target));
  for (const expected of ['src', 'other.ts', 'dynamic.ts', 'lazy.ts', 'style.css']) assert.ok(targetNames.includes(expected), expected);
  assert.ok(!targetNames.includes('fake.ts'));
  assert.ok(!graph.nodes.some(n => ['node_modules', '.env.local', 'outside'].includes(n.name)));
  assert.ok(!graph.nodes.some(n => n.kind === 'package'));
  const libraries = await analyze(root, root, true);
  assert.ok(libraries.nodes.some(n => n.id === 'package:react'));
  assert.ok(libraries.edges.some(e => e.target === 'package:react' && e.relation === 'library'));
  const child = await analyze(root, path.join(root, 'src'), false);
  assert.ok(child.nodes.some(n => n.name === 'src.ts'));
  await assert.rejects(analyze(root, os.tmpdir(), false), /프로젝트 밖/);
});
