test('detailed mode connects root files, descendants, sibling folders and containment', async t => {
  const root = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'project-flow-detail-')));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const file = name => path.join(root, name);
  await fs.mkdir(file('components/nested'), { recursive: true });
  await fs.mkdir(file('utils'));
  await fs.mkdir(file('components/.git'));
  await fs.writeFile(file('App.tsx'), "import './components/Button'; import './components/nested/Button';");
  await fs.writeFile(file('components/Button.tsx'), "import '../utils/helpers'; import './nested/Button'; import './.git/private.ts'; import './.env.local';");
  await fs.writeFile(file('components/nested/Button.tsx'), "import '../../App';");
  await fs.writeFile(file('utils/helpers.ts'), 'export const x = 1;');
  await fs.writeFile(file('components/.git/private.ts'), '');
  await fs.writeFile(file('components/.env.local'), '');
  const graph = await analyze(root, root, false, true);
  const edge = (source, target, relation) => graph.edges.some(e => e.source === file(source) && e.target === file(target) && e.relation === relation);
  assert.ok(edge('App.tsx', 'components/Button.tsx', 'import'));
  assert.ok(edge('App.tsx', 'components/nested/Button.tsx', 'import'));
  assert.ok(edge('components/Button.tsx', 'utils/helpers.ts', 'import'));
  assert.ok(edge('components/Button.tsx', 'components/nested/Button.tsx', 'import'));
  assert.ok(edge('components/nested/Button.tsx', 'App.tsx', 'import'));
  assert.ok(edge('components', 'components/Button.tsx', 'contains'));
  assert.ok(edge('components', 'components/nested/Button.tsx', 'contains'));
  assert.ok(graph.nodes.some(n => n.relativePath === path.join('components', 'nested', 'Button.tsx')));
  assert.ok(!graph.nodes.some(n => n.id.includes('.git') || n.name === '.env.local'));
  assert.equal(graph.edges.filter(e => e.target === file('components/Button.tsx') && e.relation === 'contains').length, 1);
  const collapsed = await analyze(root, root, false, false);
  assert.ok(collapsed.edges.some(e => e.source === file('App.tsx') && e.target === file('components')));
  assert.ok(!collapsed.nodes.some(n => n.parentId));
  assert.ok(!collapsed.edges.some(e => e.relation === 'contains'));
});
test('edge symbol details survive aliases, classification and folder aggregation', async t => {
  const root = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'project-flow-symbols-')));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  await fs.mkdir(path.join(root, 'src'));
  await fs.writeFile(path.join(root, 'entry.ts'), "import { run as execute, value } from './src/utils'; import type { Options } from './src/utils';");
  await fs.writeFile(path.join(root, 'src/utils.ts'), 'export function run() {}; export const value = 1; export interface Options {}');
  for (const details of [false, true]) {
    const graph = await analyze(root, root, false, details);
    const edge = graph.edges.find(e => e.source === path.join(root, 'entry.ts') && e.relation === 'import');
    assert.equal(edge.target, path.join(root, details ? 'src/utils.ts' : 'src'));
    assert.ok(edge.symbols.some(s => s.imported === 'run' && s.local === 'execute' && s.kind === 'function'));
    assert.ok(edge.symbols.some(s => s.imported === 'value' && s.kind === 'variable'));
    assert.ok(edge.symbols.some(s => s.imported === 'Options' && s.kind === 'type' && s.typeOnly));
    assert.ok(edge.symbols.every(s => s.file === 'entry.ts' && s.line === 1 && !s.targetFile));
  }
});
