'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const ts = require('typescript');
const { collectReferences, exportKinds } = require('../src/references');
const parse = text => ts.createSourceFile('test.ts', text, ts.ScriptTarget.Latest, true);
test('collect default, aliases, types, namespace, re-exports and CommonJS names', () => {
  const refs = collectReferences(parse(`import run, { value as local, type Options } from './module';
import * as utils from './module';
export { value as publicValue } from './module';
const { run: execute, value } = require('./module');
const asyncModule = await import('./module');
const direct = require('./module').run;
import compat = require('./compat');
import './style.css';
// import { fake } from './fake';`));
  const symbols = refs.get('./module');
  assert.ok(symbols.some(s => s.imported === 'default' && s.local === 'run'));
  assert.ok(symbols.some(s => s.imported === 'value' && s.local === 'local' && s.line === 1));
  assert.ok(symbols.some(s => s.imported === 'Options' && s.typeOnly));
  assert.ok(symbols.some(s => s.imported === '*' && s.local === 'utils'));
  assert.ok(symbols.some(s => s.imported === 'value' && s.local === 'publicValue' && s.syntax === 're-export'));
  assert.ok(symbols.some(s => s.imported === 'run' && s.local === 'execute' && s.syntax === 'require'));
  assert.ok(symbols.some(s => s.local === 'asyncModule' && s.syntax === 'dynamic'));
  assert.ok(symbols.some(s => s.imported === 'run' && s.syntax === 'require'));
  assert.equal(refs.get('./style.css')[0].syntax, 'side-effect');
  assert.equal(refs.get('./compat')[0].local, 'compat');
  assert.ok(!refs.has('./fake'));
});
test('classify direct exports without guessing unresolved symbol types', () => {
  const kinds = exportKinds(parse(`export function run() {};
export const value = 1, arrow = () => 2;
export class Item {}; export interface Options {}; export type ID = string;
const internal = () => 3; export { internal as other }; export default internal;`));
  assert.equal(kinds.get('run'), 'function');
  assert.equal(kinds.get('value'), 'variable');
  assert.equal(kinds.get('arrow'), 'function');
  assert.equal(kinds.get('Item'), 'class');
  assert.equal(kinds.get('Options'), 'interface');
  assert.equal(kinds.get('ID'), 'type');
  assert.equal(kinds.get('other'), 'function');
  assert.equal(kinds.get('default'), 'function');
  assert.equal(exportKinds(parse('export default function () {}')).get('default'), 'function');
});
